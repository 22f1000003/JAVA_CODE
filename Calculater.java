class Calculater {
    // Method 1: Adds two integers
    int add(int a, int b) {
        return a + b;
    }

    // Method 2: Adds three integers (Different number of parameters)
    int add(int a, int b, int c) {
        return a + b + c;
    }

    // Method 3: Adds two doubles (Different data types)
    double add(double a, double b) {
        return a + b;
    }
}